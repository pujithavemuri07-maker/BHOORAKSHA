langs = ['hi', 'te', 'ta', 'bn', 'mr', 'gu', 'kn', 'ml', 'or', 'pa', 'as', 'ur', 'sa', 'kok', 'mai', 'ks', 'ne']

def update_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    for lang in langs:
        lang_header = f'"{lang}": {{\n'
        idx = content.find(lang_header)
        if idx != -1:
            next_header = content.find('\n  "', idx + len(lang_header))
            block_end = next_header if next_header != -1 else len(content)
            block = content[idx:block_end]

            insert_lines = []
            for term, trans in ALL_TERMS.items():
                val = trans.get(lang, "")
                if not val:
                    continue
                term_json = json.dumps(term, ensure_ascii=False)
                val_json = json.dumps(val, ensure_ascii=False)
                
                # Check if term already exists
                term_pattern = rf'{re.escape(term_json)}:\s*"'
                if re.search(term_pattern, block):
                    continue
                else:
                    insert_lines.append(f'    {term_json}: {val_json},')

            if insert_lines:
                block = block[:len(lang_header)] + "\n".join(insert_lines) + "\n" + block[len(lang_header):]

            content = content[:idx] + block + content[block_end:]

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Successfully updated {filepath} with {len(ALL_TERMS)} terms across {len(langs)} languages.")

