langs = ['hi', 'te', 'ta', 'bn', 'mr', 'gu', 'kn', 'ml', 'or', 'pa', 'as', 'ur', 'sa', 'kok', 'mai', 'ks', 'ne']

for lang in langs:
    for term, trans in TERMS.items():
        val = trans.get(lang, "")
        if not val:
            continue
        # Pattern to replace existing line
        escaped_term = re.escape(term)
        pattern = rf'(\s*"{escaped_term}":\s*")[^"]*(")'
        # We need to target the section for this language
        # Find the language block
        lang_header = f'"{lang}": {{\n'
        idx = dict_content.find(lang_header)
        if idx != -1:
            next_header = dict_content.find('\n  "', idx + len(lang_header))
            block_end = next_header if next_header != -1 else len(dict_content)
            block = dict_content[idx:block_end]
            
            # check if term exists in block
            target = f'"{term}":'
            if target in block:
                # replace line
                new_block = re.sub(rf'"{escaped_term}":\s*"[^"]*"', f'"{term}": "{val}"', block)
                dict_content = dict_content[:idx] + new_block + dict_content[block_end:]
            else:
                # append to block
                insert_pos = idx + len(lang_header)
                dict_content = dict_content[:insert_pos] + f'    "{term}": "{val}",\n' + dict_content[insert_pos:]

