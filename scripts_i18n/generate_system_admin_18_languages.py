for lang in langs:
    lang_header = f'"{lang}": {{\n'
    idx = dict_content.find(lang_header)
    if idx != -1:
        next_header = dict_content.find('\n  "', idx + len(lang_header))
        block_end = next_header if next_header != -1 else len(dict_content)
        block = dict_content[idx:block_end]
        
